#define function
class function(object):
  def __init__(self,x):
    self.x=x
  def f(self,x):
    return x**3+3*x**2+3
  def df(self,x):
    return 3*x**2+6*x

#define a function that creates tangent
def tan(f,x1,x):
  y1=f.f(x1)
  m=f.df(x1)
  return m*(x-x1)+y1

def learn(f, x_ini, tolerance, epoch):
  x1 = x_ini
  history = {'x': [], 'y': [], 'm': []}
  print(f"{'Iteration':<10} {'x1 (Current Guess)':<20} {'f(x1)':<15}")
  print("-" * 50)
  for i in range(epoch):
    y1 = f.f(x1)
    m = f.df(x1)

    history['x'].append(x1)
    history['y'].append(y1)
    history['m'].append(m)

    print(f"{i:<10} {x1:<20.6f} {y1:<15.6f}")
    if abs(y1) < tolerance:
      return x1, history
    if m == 0:
      print("Slope is zero. Newton's Method failed.")
      return None, history
    x1 = x1 - y1 / m
  return x1, history

func_instance = function(3.0)

root, history = learn(func_instance, 3.0, 1e-16, 500)
print("-" * 50)
print(f"Final Root Found: {root:.6f}")

"""### Visualize Newton's Method Animation"""
import matplotlib
