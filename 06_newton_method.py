ax.set_title("Newton's Method Step-by-Step Visualization")
ax.set_xlabel("x")
ax.set_ylabel("f(x)")
ax.grid(True, linestyle=':', alpha=0.6)

# Dynamic points
curr_point, = ax.plot([], [], 'ro', markersize=8, label='Current Guess')
next_point, = ax.plot([], [], 'go', markersize=8, label='New Guess')

# Dynamic lines
tangent_line, = ax.plot([], [], 'r--', linewidth=1.5, label='Tangent Line')
vertical_line, = ax.plot([], [], 'g:', linewidth=1.5, label='Vertical Step to Curve')

ax.legend(loc='upper left')

def animate(i):
    x_i = history['x'][i]
    y_i = history['y'][i]
    m_i = history['m'][i]
    
    # Update current point on the function
    curr_point.set_data([x_i], [y_i])
    
    # If it's the last frame, just keep the point and clear lines
    if i == len(history['x']) - 1:
        tangent_line.set_data([], [])
        vertical_line.set_data([], [])
        next_point.set_data([], [])
        return curr_point, tangent_line, vertical_line, next_point

    # Calculate the next step intersection with x-axis
    x_next = history['x'][i + 1]
    y_next = history['y'][i + 1]

    # Tangent line goes from current point (x_i, y_i) to x-axis intercept (x_next, 0)
    tangent_x = [x_i, x_next]
    tangent_y = [y_i, 0]
    tangent_line.set_data(tangent_x, tangent_y)
    
    # Update the green point showing the new guess on the x-axis
    next_point.set_data([x_next], [0])

    # Vertical line goes from x-axis intercept (x_next, 0) up/down to the function (x_next, y_next)
    vert_x = [x_next, x_next]
    vert_y = [0, y_next]
    vertical_line.set_data(vert_x, vert_y)

    return curr_point, tangent_line, vertical_line, next_point

ani = animation.FuncAnimation(
    fig, animate, frames=len(history['x']), interval=1500, blit=True, cache_frame_data=False
)

plt.show(block=True)